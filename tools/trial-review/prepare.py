#!/usr/bin/env python3
"""Materialize an isolated desktop project. Never change the study's Unity settings."""
from pathlib import Path
import argparse
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"Shared source changed; review adapter boundary: {old[:90]}")
    return text.replace(old, new, 1)


def prepare(project):
    project = project.resolve()
    if project == ROOT or ROOT in project.parents:
        raise ValueError("Generated project must be outside the study checkout")
    marker = project / '.trial-review-generated'
    if project.exists() and any(project.iterdir()) and not marker.exists():
        raise ValueError("Refusing to overwrite an unrelated directory")
    project.mkdir(parents=True, exist_ok=True)
    marker.write_text('generated by tools/trial-review/prepare.py\n')
    assets = project / 'Assets'
    shared = assets / 'SharedReplay'
    shared.mkdir(parents=True, exist_ok=True)
    hashes = {}

    def source(relative):
        data = (ROOT / relative).read_bytes()
        hashes[relative] = hashlib.sha256(data).hexdigest()
        return data.decode('utf-8')

    for name in ['TrialReplayData', 'TrialReplayState', 'TrialReplayFile', 'TrialReplayAudio']:
        (shared / (name + '.cs')).write_text(source('Assets/Replay/' + name + '.cs'))
    # Pure data/policy dependencies only; no recorders, bootstraps, credentials or XR.
    for name in ['GuidanceDecision', 'GazeObservation', 'GazeTargetHistory', 'DirectionalHintPolicy']:
        (shared / (name + '.cs')).write_text(source('Assets/' + name + '.cs'))

    audio = source('Assets/Editor/TrialReplayAudioPreview.cs')
    audio = replace_once(audio, 'using UnityEditor.SceneManagement;\n', '')
    start = audio.index('    public sealed class EditorOutput : IOutput, IDisposable')
    end = audio.index('    public readonly TrialReplayAudioPlan Plan;', start)
    audio = audio[:start] + audio[end:]
    audio = replace_once(audio, 'output ?? new EditorOutput()', 'output ?? throw new ArgumentNullException(nameof(output))')
    (shared / 'TrialReplayAudioPreview.cs').write_text(audio)

    renderer = source('Assets/Editor/TrialReplayRenderer.cs')
    renderer = replace_once(renderer, 'using UnityEditor;\n', '')
    # The study uses the right controller. Retain historical left-hand data/model, but suppress its ray.
    renderer = replace_once(renderer,
        'DrawController(m_LeftRay, forceVisible ? null : sample?.leftController);',
        'DrawController(m_LeftRay, null); // Left-controller ray intentionally omitted in desktop replay.')
    renderer = replace_once(renderer, 'readonly PreviewRenderUtility m_Preview = new PreviewRenderUtility();',
                            'readonly Camera m_Camera;\n    RenderTexture m_Texture;')
    renderer = replace_once(renderer, 'public Camera Camera => m_Preview.camera;', 'public Camera Camera => m_Camera;')
    renderer = replace_once(renderer, '        m_Preview.camera.clearFlags',
                            '        m_Camera = new GameObject("Replay camera").AddComponent<Camera>();\n        m_Camera.enabled = false;\n        m_Camera.clearFlags')
    renderer = renderer.replace('m_Preview.camera', 'm_Camera')
    renderer = replace_once(renderer, '        m_Preview.AddSingleGO(m_Root);', '')
    start = renderer.index('    public Texture Render(Rect rect)')
    end = renderer.index('    public void Dispose()', start)
    renderer = renderer[:start] + '''    public Texture Render(Rect rect)
    {
        int width = Math.Max(1, (int)rect.width), height = Math.Max(1, (int)rect.height);
        if (m_Texture == null || m_Texture.width != width || m_Texture.height != height)
        {
            if (m_Texture != null) { m_Texture.Release(); UnityEngine.Object.DestroyImmediate(m_Texture); }
            m_Texture = new RenderTexture(width, height, 24);
        }
        Camera.targetTexture = m_Texture;
        Camera.aspect = (float)width / height;
        Camera.Render();
        return m_Texture;
    }

''' + renderer[end:]
    renderer = replace_once(renderer, '        m_Preview.Cleanup();',
                            '        if (m_Texture != null) { m_Texture.Release(); UnityEngine.Object.DestroyImmediate(m_Texture); }\n        UnityEngine.Object.DestroyImmediate(m_Camera.gameObject);\n        UnityEngine.Object.DestroyImmediate(m_Root);')
    (shared / 'TrialReplayRenderer.cs').write_text(renderer)
    for directory in ['Runtime', 'Editor', 'ThirdParty', 'Resources']:
        shutil.copytree(HERE / directory, assets / directory, dirs_exist_ok=True)
    # HTC source remains in the installed SDK, not redistributed in this tool's source.
    packages = sorted((ROOT / 'Library/PackageCache').glob('com.htc.upm.vive.openxr@*'))
    if len(packages) != 1:
        raise ValueError('Resolve exactly one installed VIVE OpenXR package before building')
    htc = packages[0]
    controller_dir = htc / 'Samples~/Toolkits/Toolkits/Common/Models/Controller'
    destination = assets / 'ThirdParty/ViveControllers'
    destination.mkdir(parents=True, exist_ok=True)
    for hand in ['L', 'R']:
        for suffix in ['.fbx', '.fbx.meta']:
            original = controller_dir / ('Focus3Model' + hand + suffix)
            shutil.copyfile(original, destination / original.name)
            hashes[str(original.relative_to(ROOT))] = hashlib.sha256(original.read_bytes()).hexdigest()
    shutil.copyfile(htc / 'LICENSE.txt', destination / 'LICENSE.txt')
    notices = assets / 'StreamingAssets/ThirdPartyNotices'
    notices.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(htc / 'LICENSE.txt', notices / 'HTC-LICENSE.txt')
    shutil.copyfile(HERE / 'ThirdParty/KenneyProtagonists/License.txt', notices / 'Kenney-LICENSE.txt')
    shutil.copyfile(HERE / 'ThirdParty/KenneyProtagonists/SOURCE.md', notices / 'Kenney-SOURCE.md')
    (project / 'Packages').mkdir(exist_ok=True)
    (project / 'Packages/manifest.json').write_text(json.dumps({'dependencies': {
        'com.unity.modules.audio': '1.0.0', 'com.unity.modules.animation': '1.0.0', 'com.unity.modules.imgui': '1.0.0',
        'com.unity.modules.jsonserialize': '1.0.0', 'com.unity.modules.imageconversion': '1.0.0',
        'com.unity.modules.physics': '1.0.0', 'com.unity.modules.screencapture': '1.0.0'}}, indent=2))
    (project / 'ProjectSettings').mkdir(exist_ok=True)
    shutil.copyfile(ROOT / 'ProjectSettings/ProjectVersion.txt', project / 'ProjectSettings/ProjectVersion.txt')
    (project / 'shared-source-sha256.json').write_text(json.dumps(hashes, indent=2))
    return project


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('project', type=Path)
    args = parser.parse_args()
    print(prepare(args.project))
